using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Ambitions;

[GenerateTypedNameReferences]
public sealed partial class SS220AmbitionControl : Control
{
    public event Action? OnDeleteAmbitionRequest;

    public SS220AmbitionControl(string title, string description)
    {
        RobustXamlLoader.Load(this);
        TitleLabel.SetMessage(title);
        DescLabel.SetMessage(description);
        DeleteButton.OnPressed += _ => OnDeleteAmbitionRequest?.Invoke();
    }
}
