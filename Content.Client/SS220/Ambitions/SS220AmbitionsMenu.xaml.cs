using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared.SS220.Ambitions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.SS220.Ambitions;

[GenerateTypedNameReferences]
public sealed partial class SS220AmbitionsMenu : FancyWindow
{
    public event Action<int>? OnNewAmbitionRequest;
    public event Action<int>? OnLockAmbitionRequest;
    public event Action<EntProtoId, int>? OnDeleteAmbitionRequest;
    private int _revision;

    public SS220AmbitionsMenu()
    {
        RobustXamlLoader.Load(this);
        AddAmbitionButton.Disabled = true;
        LockAmbitionButton.Disabled = true;
        AddAmbitionButton.OnPressed += _ => OnNewAmbitionRequest?.Invoke(_revision);
        LockAmbitionButton.OnPressed += _ => OnLockAmbitionRequest?.Invoke(_revision);
    }

    public void Update(SS220AmbitionsBuiState state)
    {
        _revision = state.Revision;
        AmbitionsContainer.RemoveAllChildren();
        LockAmbitionButton.Disabled = false;
        AddAmbitionButton.Text = Loc.GetString("ss220-ambitions-buttons-add-count",
            ("count", state.Ambitions.Count), ("max", state.MaxAmbitions), ("remaining", state.Rerolls));
        AddAmbitionButton.Disabled = state.Ambitions.Count >= state.MaxAmbitions || state.Rerolls <= 0;
        ErrorLabel.SetMessage(state.Error ?? string.Empty);
        ErrorLabel.Visible = state.Error != null;

        foreach (var ambition in state.Ambitions)
        {
            var control = new SS220AmbitionControl(ambition.Title, ambition.Description);
            control.OnDeleteAmbitionRequest += () => OnDeleteAmbitionRequest?.Invoke(ambition.Prototype, state.Revision);
            AmbitionsContainer.AddChild(control);
        }
    }
}
